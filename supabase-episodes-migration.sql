create table if not exists public.episodes (
  id bigint generated by default as identity primary key,
  anime_id bigint not null references public.anime(id) on delete cascade,
  episode_number integer not null,
  title text not null,
  drive_file_id text not null,
  video_url text not null,
  created_at timestamptz not null default now(),
  unique (anime_id, drive_file_id)
);
alter table public.episodes enable row level security;
drop policy if exists "Public can read episodes" on public.episodes;
create policy "Public can read episodes" on public.episodes for select to anon, authenticated using (true);
drop policy if exists "Admins can insert episodes" on public.episodes;
create policy "Admins can insert episodes" on public.episodes for insert to authenticated with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));
drop policy if exists "Admins can update episodes" on public.episodes;
create policy "Admins can update episodes" on public.episodes for update to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin')) with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));
drop policy if exists "Admins can delete episodes" on public.episodes;
create policy "Admins can delete episodes" on public.episodes for delete to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));
