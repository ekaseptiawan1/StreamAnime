-- Jalankan sekali di Supabase Dashboard > SQL Editor.
-- Mendukung banyak produk affiliate yang dapat ditambah, diedit, dan dihapus dari Admin.
create table if not exists public.site_banners (
  id bigint generated by default as identity primary key,
  title text not null default 'Produk Shopee',
  image_url text not null,
  target_url text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Migrasi aman dari versi banner tunggal sebelumnya (id=1).
alter table public.site_banners drop constraint if exists site_banners_id_check;
alter table public.site_banners alter column id type bigint;
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'site_banners'
      and column_name = 'id' and is_identity = 'YES'
  ) then
    alter table public.site_banners alter column id add generated by default as identity;
  end if;
end $$;
select setval(
  pg_get_serial_sequence('public.site_banners', 'id'),
  coalesce(max(id), 1),
  coalesce(max(id), 0) > 0
) from public.site_banners;
alter table public.site_banners add column if not exists title text not null default 'Produk Shopee';
alter table public.site_banners add column if not exists created_at timestamptz not null default now();
alter table public.site_banners add column if not exists updated_at timestamptz not null default now();

alter table public.site_banners enable row level security;

drop policy if exists "Public can read active site banner" on public.site_banners;
drop policy if exists "Public can read active site banners" on public.site_banners;
create policy "Public can read active site banners"
on public.site_banners for select to anon, authenticated
using (is_active = true);

drop policy if exists "Admins can read all site banners" on public.site_banners;
create policy "Admins can read all site banners"
on public.site_banners for select to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

drop policy if exists "Admins can insert site banners" on public.site_banners;
create policy "Admins can insert site banners"
on public.site_banners for insert to authenticated
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

drop policy if exists "Admins can update site banners" on public.site_banners;
create policy "Admins can update site banners"
on public.site_banners for update to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

drop policy if exists "Admins can delete site banners" on public.site_banners;
create policy "Admins can delete site banners"
on public.site_banners for delete to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
