-- Jalankan seluruh file ini di Supabase Dashboard > SQL Editor.
-- Buat akun admin terlebih dahulu melalui Authentication > Users > Add user.
-- Setelah akun dibuat, salin UUID user lalu jalankan perintah UPDATE di bagian paling bawah.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.anime (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  poster_url text,
  genre text,
  video_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.anime enable row level security;

drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile" on public.profiles
for select to authenticated using (id = auth.uid());

drop policy if exists "Public can read anime" on public.anime;
create policy "Public can read anime" on public.anime
for select to anon, authenticated using (true);

drop policy if exists "Admins can insert anime" on public.anime;
create policy "Admins can insert anime" on public.anime
for insert to authenticated with check (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
);

drop policy if exists "Admins can update anime" on public.anime;
create policy "Admins can update anime" on public.anime
for update to authenticated using (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
) with check (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
);

drop policy if exists "Admins can delete anime" on public.anime;
create policy "Admins can delete anime" on public.anime
for delete to authenticated using (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
);

-- Bucket publik agar video dapat diputar oleh pengunjung website.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('anime-videos', 'anime-videos', true, 104857600, array['video/mp4','video/webm','video/ogg'])
on conflict (id) do update set public = true, file_size_limit = 104857600,
  allowed_mime_types = array['video/mp4','video/webm','video/ogg'];

drop policy if exists "Public can view anime videos" on storage.objects;
create policy "Public can view anime videos" on storage.objects
for select to anon, authenticated using (bucket_id = 'anime-videos');

drop policy if exists "Admins can upload anime videos" on storage.objects;
create policy "Admins can upload anime videos" on storage.objects
for insert to authenticated with check (
  bucket_id = 'anime-videos' and (storage.foldername(name))[1] = auth.uid()::text
  and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
);

drop policy if exists "Admins can update anime videos" on storage.objects;
create policy "Admins can update anime videos" on storage.objects
for update to authenticated using (
  bucket_id = 'anime-videos' and (storage.foldername(name))[1] = auth.uid()::text
  and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
) with check (
  bucket_id = 'anime-videos' and (storage.foldername(name))[1] = auth.uid()::text
  and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
);

drop policy if exists "Admins can delete anime videos" on storage.objects;
create policy "Admins can delete anime videos" on storage.objects
for delete to authenticated using (
  bucket_id = 'anime-videos' and (storage.foldername(name))[1] = auth.uid()::text
  and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
);

